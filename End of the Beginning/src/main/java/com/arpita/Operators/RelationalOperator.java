package com.arpita.Operators;

public class RelationalOperator {
    public static void main(String[] args){

        int j= 8;
        int k= 1;

        System.out.println(j>k);
        System.out.println(j<k);
        System.out.println(j==k);
        System.out.println(j!=k);
        System.out.println(j>=k);
        System.out.println(j<=k);
    }
}
