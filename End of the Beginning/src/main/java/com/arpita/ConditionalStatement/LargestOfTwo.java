package com.arpita.ConditionalStatement;

public class LargestOfTwo {
    public static void main(String[] args){

        int a=90;
        int b=1000;

        if(a>b){
            System.out.println("Largest : " + a);
        }
        else{
            System.out.println("Largest :" + b);
        }
    }

}
