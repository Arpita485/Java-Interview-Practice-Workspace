public class Variable {

    //static (class variable shared across all object)
    static String movie= "PVR";


    //instance variable (object variable)

    int c=9;

    public static void main(String[] args){

        //Local Variable( Scope:- inside method)
        int a = 4;
        System.out.println(a);

        //final variable (can't change)
        final int i=7;
    }
}
